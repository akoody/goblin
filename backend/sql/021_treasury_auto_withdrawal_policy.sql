CREATE TABLE IF NOT EXISTS treasury_auto_withdrawal_policy (
  id TINYINT UNSIGNED NOT NULL PRIMARY KEY,
  network VARCHAR(32) NOT NULL DEFAULT 'TRON',
  currency VARCHAR(16) NOT NULL DEFAULT 'USDT',
  destination_address VARCHAR(255) NULL,
  threshold_amount DECIMAL(36,18) NOT NULL DEFAULT 100,
  enabled TINYINT(1) NOT NULL DEFAULT 0,
  updated_by BIGINT UNSIGNED NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

