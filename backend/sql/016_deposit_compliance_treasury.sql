CREATE TABLE IF NOT EXISTS deposit_reviews (
 deposit_id BIGINT UNSIGNED PRIMARY KEY,
 status VARCHAR(24) NOT NULL DEFAULT 'PENDING_AML',
 fee_usd DECIMAL(12,2) NOT NULL,
 min_usd DECIMAL(12,2) NOT NULL,
 fee_amount DECIMAL(36,18) NULL,
 net_amount DECIMAL(36,18) NULL,
 quote_price DECIMAL(36,18) NULL,
 quote_source VARCHAR(40) NULL,
 quote_at TIMESTAMP(3) NULL,
 report_provider VARCHAR(120) NULL,
 report_reference VARCHAR(1000) NULL,
 risk_level VARCHAR(16) NULL,
 review_note VARCHAR(2000) NULL,
 reviewer_id BIGINT UNSIGNED NULL,
 reviewed_at TIMESTAMP NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_review_deposit FOREIGN KEY (deposit_id) REFERENCES blockchain_deposits(id),
 KEY idx_deposit_review_status (status,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS admin_treasury (
 currency VARCHAR(16) PRIMARY KEY,
 balance DECIMAL(36,18) NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS admin_treasury_ledger (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 deposit_id BIGINT UNSIGNED NOT NULL UNIQUE,
 user_id BIGINT UNSIGNED NOT NULL,
 currency VARCHAR(16) NOT NULL,
 amount DECIMAL(36,18) NOT NULL,
 fee_usd DECIMAL(12,2) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_treasury_deposit FOREIGN KEY (deposit_id) REFERENCES blockchain_deposits(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS deposit_policy_audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 actor_id BIGINT UNSIGNED NOT NULL,
 previous_fee DECIMAL(12,2) NOT NULL,
 new_fee DECIMAL(12,2) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
