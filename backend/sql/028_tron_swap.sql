CREATE TABLE IF NOT EXISTS tron_swap_policy (
 id TINYINT PRIMARY KEY,
 enabled TINYINT NOT NULL DEFAULT 0,
 minimum_trx DECIMAL(30,6) NOT NULL DEFAULT 10,
 minimum_usdt DECIMAL(30,6) NOT NULL DEFAULT 5,
 fee_budget_trx DECIMAL(30,6) NOT NULL DEFAULT 150,
 updated_by BIGINT UNSIGNED NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
INSERT IGNORE INTO tron_swap_policy(id) VALUES(1);
CREATE TABLE IF NOT EXISTS tron_swaps (
 id CHAR(36) PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 request_key VARCHAR(128) NOT NULL,
 input_currency VARCHAR(8) NOT NULL,
 input_amount DECIMAL(30,6) NOT NULL,
 expected_output DECIMAL(30,6) NOT NULL,
 minimum_output DECIMAL(30,6) NOT NULL,
 address VARCHAR(64) NOT NULL,
 quote_expires_at TIMESTAMP NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'quoted',
 steps_json JSON NULL,
 step_index INT NOT NULL DEFAULT 0,
 reserve_trx DECIMAL(30,6) NOT NULL DEFAULT 0,
 fee_limit_sun BIGINT UNSIGNED NOT NULL DEFAULT 0,
 fee_charged DECIMAL(30,6) NOT NULL DEFAULT 0,
 actual_output DECIMAL(30,6) NULL,
 error_code VARCHAR(80) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uq_tron_swap_request(user_id,request_key),
 KEY idx_tron_swap_status(status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS tron_swap_transactions (
 swap_id CHAR(36) NOT NULL,
 step_index INT NOT NULL,
 tx_hash VARCHAR(128) NOT NULL UNIQUE,
 signed_json JSON NOT NULL,
 receipt_json JSON NULL,
 PRIMARY KEY(swap_id,step_index)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS tron_swap_policy_audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 actor_id BIGINT UNSIGNED NOT NULL,
 policy_json JSON NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
