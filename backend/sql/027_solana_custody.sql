CREATE TABLE IF NOT EXISTS solana_accounts (
 user_id BIGINT UNSIGNED PRIMARY KEY,
 address VARCHAR(64) NOT NULL UNIQUE,
 encrypted_key TEXT NOT NULL,
 last_signature VARCHAR(128) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS solana_holdings (
 user_id BIGINT UNSIGNED NOT NULL,
 mint VARCHAR(64) NOT NULL,
 decimals TINYINT UNSIGNED NOT NULL,
 amount_atomic DECIMAL(65,0) NOT NULL DEFAULT 0,
 PRIMARY KEY(user_id,mint)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS solana_receipts (
 signature VARCHAR(128) NOT NULL,
 event_index INT NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 mint VARCHAR(64) NOT NULL,
 amount_atomic DECIMAL(65,0) NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'credited',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(signature,event_index,user_id,mint)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS solana_swap_policy (
 id TINYINT PRIMARY KEY,
 enabled TINYINT NOT NULL DEFAULT 0,
 minimum_sol DECIMAL(20,9) NOT NULL DEFAULT 0.01,
 max_fee_sol DECIMAL(20,9) NOT NULL DEFAULT 0.01,
 updated_by BIGINT UNSIGNED NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
