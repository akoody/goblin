CREATE TABLE IF NOT EXISTS solana_swaps (
 id CHAR(36) PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 request_key VARCHAR(128) NOT NULL,
 mint VARCHAR(64) NOT NULL,
 decimals TINYINT UNSIGNED NOT NULL,
 input_atomic DECIMAL(65,0) NOT NULL,
 reserve_atomic DECIMAL(65,0) NOT NULL,
 minimum_output DECIMAL(65,0) NOT NULL,
 quote_json JSON NOT NULL,
 expires_at TIMESTAMP NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'quoted',
 signature VARCHAR(128) NULL UNIQUE,
 signed_transaction MEDIUMTEXT NULL,
 output_atomic DECIMAL(65,0) NULL,
 cost_atomic DECIMAL(65,0) NULL,
 error_code VARCHAR(80) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uq_solana_request(user_id,request_key),
 KEY idx_solana_status(status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS solana_policy_audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 actor_id BIGINT UNSIGNED NOT NULL,
 policy_json JSON NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
