SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS processing_deals (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    user_id BIGINT UNSIGNED NULL,
    title VARCHAR(160) NOT NULL,
    direction VARCHAR(16) NOT NULL DEFAULT 'IN',
    fiat_currency VARCHAR(8) NOT NULL DEFAULT 'RUB',
    target_amount DECIMAL(36,18) NOT NULL,
    processed_amount DECIMAL(36,18) NOT NULL DEFAULT 0,
    min_transaction_amount DECIMAL(36,18) NOT NULL DEFAULT 0,
    max_transaction_amount DECIMAL(36,18) NOT NULL DEFAULT 0,
    status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
    comment VARCHAR(1000) NULL,
    created_by BIGINT UNSIGNED NULL,
    completed_at DATETIME NULL,
    cancelled_at DATETIME NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_processing_deals_user (user_id),
    KEY idx_processing_deals_status_created (status, created_at),
    KEY idx_processing_deals_currency_status (fiat_currency, status),
    CONSTRAINT fk_processing_deal_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_processing_deal_admin FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS processing_requisites (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    deal_id BIGINT UNSIGNED NOT NULL,
    method_code VARCHAR(64) NOT NULL DEFAULT 'manual',
    label VARCHAR(160) NOT NULL,
    holder_name VARCHAR(160) NULL,
    bank_name VARCHAR(160) NULL,
    account_number VARCHAR(255) NULL,
    card_number VARCHAR(64) NULL,
    phone VARCHAR(64) NULL,
    iban VARCHAR(64) NULL,
    details JSON NULL,
    fiat_currency VARCHAR(8) NOT NULL DEFAULT 'RUB',
    limit_amount DECIMAL(36,18) NOT NULL DEFAULT 0,
    used_amount DECIMAL(36,18) NOT NULL DEFAULT 0,
    min_transaction_amount DECIMAL(36,18) NOT NULL DEFAULT 0,
    max_transaction_amount DECIMAL(36,18) NOT NULL DEFAULT 0,
    priority INT NOT NULL DEFAULT 100,
    status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_processing_requisites_deal (deal_id),
    KEY idx_processing_requisites_status_priority (status, priority),
    CONSTRAINT fk_processing_requisite_deal FOREIGN KEY (deal_id) REFERENCES processing_deals (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS processing_transactions (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    deal_id BIGINT UNSIGNED NOT NULL,
    requisite_id BIGINT UNSIGNED NULL,
    user_id BIGINT UNSIGNED NULL,
    external_id VARCHAR(120) NULL,
    amount DECIMAL(36,18) NOT NULL,
    fiat_currency VARCHAR(8) NOT NULL DEFAULT 'RUB',
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    payer_name VARCHAR(160) NULL,
    payer_account VARCHAR(255) NULL,
    proof_url VARCHAR(500) NULL,
    comment VARCHAR(1000) NULL,
    confirmed_at DATETIME NULL,
    failed_at DATETIME NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_processing_transactions_external (external_id),
    KEY idx_processing_transactions_deal (deal_id),
    KEY idx_processing_transactions_requisite (requisite_id),
    KEY idx_processing_transactions_status_created (status, created_at),
    CONSTRAINT fk_processing_transaction_deal FOREIGN KEY (deal_id) REFERENCES processing_deals (id) ON DELETE CASCADE,
    CONSTRAINT fk_processing_transaction_requisite FOREIGN KEY (requisite_id) REFERENCES processing_requisites (id) ON DELETE SET NULL,
    CONSTRAINT fk_processing_transaction_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
