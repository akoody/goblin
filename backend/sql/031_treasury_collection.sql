CREATE TABLE treasury_collection_wallets (
 network VARCHAR(16) PRIMARY KEY, currency VARCHAR(16) NOT NULL,
 address VARCHAR(128) NOT NULL UNIQUE, encrypted_key TEXT NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE treasury_collection_policy (
 network VARCHAR(16) PRIMARY KEY, mode VARCHAR(16) NOT NULL DEFAULT 'manual',
 threshold_amount DECIMAL(36,9) NOT NULL, updated_by BIGINT UNSIGNED NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
