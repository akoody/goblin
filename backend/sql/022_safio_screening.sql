CREATE TABLE IF NOT EXISTS deposit_aml_checks (
 deposit_id BIGINT UNSIGNED PRIMARY KEY,
 provider VARCHAR(24) NOT NULL DEFAULT 'Safio',
 check_id VARCHAR(64) NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'pending',
 attempts INT UNSIGNED NOT NULL DEFAULT 0,
 next_attempt_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 result_json JSON NULL,
 error_code VARCHAR(80) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_aml_check_deposit FOREIGN KEY (deposit_id) REFERENCES blockchain_deposits(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
