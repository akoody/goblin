CREATE TABLE IF NOT EXISTS pump_policy (
 id TINYINT PRIMARY KEY, enabled TINYINT NOT NULL DEFAULT 0,
 service_fee_sol DECIMAL(20,9) NOT NULL DEFAULT 1,
 minimum_buy_sol DECIMAL(20,9) NOT NULL DEFAULT 0.2,
 network_budget_sol DECIMAL(20,9) NOT NULL DEFAULT 0.05,
 updated_by BIGINT UNSIGNED NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
INSERT IGNORE INTO pump_policy(id) VALUES(1);
CREATE TABLE IF NOT EXISTS pump_launches (
 id CHAR(36) PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 request_key VARCHAR(128) NOT NULL, mint VARCHAR(64) NOT NULL UNIQUE,
 encrypted_mint_key TEXT NULL, name VARCHAR(128) NOT NULL, symbol VARCHAR(52) NOT NULL,
 metadata_json JSON NOT NULL, image_data MEDIUMTEXT NOT NULL,
 buy_atomic DECIMAL(65,0) NOT NULL, service_fee_atomic DECIMAL(65,0) NOT NULL,
 network_budget_atomic DECIMAL(65,0) NOT NULL, reserve_atomic DECIMAL(65,0) NOT NULL,
 minimum_output DECIMAL(65,0) NULL, output_atomic DECIMAL(65,0) NULL,
 cost_atomic DECIMAL(65,0) NULL, status VARCHAR(24) NOT NULL DEFAULT 'draft',
 signature VARCHAR(128) NULL UNIQUE, signed_transaction MEDIUMTEXT NULL,
 last_valid_height BIGINT UNSIGNED NULL, error_code VARCHAR(80) NULL,
 expires_at TIMESTAMP NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_pump_request(user_id,request_key), KEY idx_pump_status(status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS pump_fee_ledger (
 launch_id CHAR(36) PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 amount_sol DECIMAL(20,9) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS pump_policy_audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actor_id BIGINT UNSIGNED NOT NULL,
 policy_json JSON NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
